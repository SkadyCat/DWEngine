"""Export CSS alpha masks, leaving the original icon pixels untouched.

Only near-black pixels connected to an image edge are eligible. Enclosed dark
details stay opaque. The 18..30 RGB-max transition feathers the background edge.
Run from any directory: python Tools/UI/Export-EquipmentIconMasks.py
"""
from collections import deque
import hashlib
import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PUBLIC = ROOT / 'CustomTools/RuleStudio/public'
ICONS = PUBLIC / 'assets/icons/warcraft-v1'
OUTPUT = PUBLIC / 'assets/ui/equipment-masks'
LOW, HIGH = 18, 30


def background_mask(image):
    pixels = np.asarray(image.convert('RGBA'))
    brightness = pixels[:, :, :3].max(axis=2)
    eligible = (brightness < HIGH) | (pixels[:, :, 3] == 0)
    height, width = eligible.shape
    outside = np.zeros((height, width), dtype=bool)
    queue = deque()

    def add(x, y):
        if eligible[y, x] and not outside[y, x]:
            outside[y, x] = True
            queue.append((x, y))

    for x in range(width):
        add(x, 0)
        add(x, height - 1)
    for y in range(height):
        add(0, y)
        add(width - 1, y)
    while queue:
        x, y = queue.popleft()
        if x:
            add(x - 1, y)
        if x + 1 < width:
            add(x + 1, y)
        if y:
            add(x, y - 1)
        if y + 1 < height:
            add(x, y + 1)

    transition = np.clip((brightness.astype(float) - LOW) / (HIGH - LOW), 0, 1)
    transition = transition * transition * (3 - 2 * transition)
    alpha = np.full((height, width), 255, dtype=np.uint8)
    alpha[outside] = np.rint(transition[outside] * 255).astype(np.uint8)
    # Keep an unexpectedly dark icon usable instead of silently erasing it.
    skipped = float(np.mean(alpha > 0)) < .08
    if skipped:
        alpha.fill(255)
    return Image.merge('LA', (Image.new('L', image.size, 255), Image.fromarray(alpha))), skipped


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    sources = sorted((ICONS / 'equipment').glob('*.png')) + [ICONS / 'fallback/equipment.png']
    css = ['/* Generated by Tools/UI/Export-EquipmentIconMasks.py. Alpha masks only. */']
    manifest = {'method': 'edge-connected-near-black', 'low': LOW, 'high': HIGH, 'icons': []}
    for source in sources:
        original = source.read_bytes()
        source_hash = hashlib.sha256(original).hexdigest()
        image = Image.open(source)
        mask, skipped = background_mask(image)
        name = source.stem if source.parent.name == 'equipment' else 'fallback-equipment'
        target = OUTPUT / (name + '.png')
        mask.save(target, optimize=True)
        icon_url = '/' + source.relative_to(PUBLIC).as_posix()
        mask_url = '/' + target.relative_to(PUBLIC).as_posix()
        css.append(f'img.game-icon[src="{icon_url}"] {{ --equipment-icon-mask: url("{mask_url}"); }}')
        alpha = np.asarray(mask.getchannel('A'))
        manifest['icons'].append({'source': icon_url, 'mask': mask_url, 'sourceSha256': source_hash,
                                  'sourceMode': image.mode, 'size': list(image.size), 'skipped': skipped,
                                  'transparentPixels': int(np.sum(alpha == 0)), 'pixels': int(alpha.size)})
        assert hashlib.sha256(source.read_bytes()).hexdigest() == source_hash, source
    (OUTPUT / 'catalog.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    # UICreator and native UMG consume the same alpha as the browser CSS mask.
    # Keep derived RGBA artwork separate from the original RGB icon library.
    native = ROOT / 'Content/OpusIconsMasked/equipment'
    native.mkdir(parents=True, exist_ok=True)
    for source in sorted((ROOT / 'Content/OpusIcons/equipment').glob('*.png')):
        image = Image.open(source).convert('RGBA')
        mask, _ = background_mask(image)
        image.putalpha(mask.getchannel('A'))
        image.save(native / source.name, optimize=True)
    tool = ROOT / 'CustomTools/UICreatorAlpha/src/assets/rulestudio-hud'
    provenance = json.loads((tool / 'svg/original-art/provenance.json').read_text(encoding='utf-8'))
    artwork = {}
    for item in provenance['icons']:
        source = Path(item['source'].replace('\\', '/'))
        if source.parent.name != 'equipment':
            continue
        actual = ICONS / 'equipment' / source.name
        image = Image.open(actual).convert('RGBA')
        mask, _ = background_mask(image)
        image.putalpha(mask.getchannel('A'))
        from io import BytesIO
        encoded = BytesIO()
        image.save(encoded, format='PNG', optimize=True)
        artwork[item['id']] = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96"><image width="96" height="96" href="data:image/png;base64,' + base64.b64encode(encoded.getvalue()).decode() + '"/></svg>'
    (tool / 'equipment-art.js').write_text('// Generated by Export-EquipmentIconMasks.py. Original RGB + shared alpha.\nexport const equipmentArt = ' + json.dumps(artwork, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(json.dumps({'masks': len(sources), 'skipped': sum(i['skipped'] for i in manifest['icons']),
                      'sourceImagesUnchanged': True, 'output': str(OUTPUT)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
