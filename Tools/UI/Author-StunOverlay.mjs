import fs from 'node:fs/promises';
import path from 'node:path';
import {ProjectRepository} from '../../CustomTools/UICreatorAlpha/server/project-repository.mjs';
import {validateDocument} from '../../CustomTools/UICreatorAlpha/src/core/model.js';
import {installStunCrust,createPlayerStunProject,stunOverlaySvg,STUN_YELLOW} from '../../CustomTools/UICreatorAlpha/src/assets/world-overlays/stun-crust.js';
const root=path.resolve(import.meta.dirname,'../..'),proof=path.join(root,'Saved/Verification/StunOverlay');
await fs.mkdir(proof,{recursive:true});
const repo=new ProjectRepository(path.join(root,'CustomTools/UICreatorAlpha/data/projects'));
const mirror=new ProjectRepository(path.join(root,'UIAuthoring/projects'));
async function save(doc,previous){const errors=validateDocument(doc);if(errors.length)throw Error(errors.join('\n'));const result=await repo.write(doc,previous?.revision||0);await mirror.write(doc,(await mirror.pointer(doc.id))?.revision||0);return result;}
const worldRecord=await repo.read('opus-world-overlays-20261025');
await fs.writeFile(path.join(proof,'world-before.json'),JSON.stringify(worldRecord));
const world=installStunCrust(structuredClone(worldRecord.document)),worldSaved=await save(world,worldRecord);
await fs.writeFile(path.join(root,'UIAuthoring/WorldOverlays.uialpha.json'),JSON.stringify(world,null,2));
const hudRecord=await repo.read('hud-darksteel-20261024'),hud=structuredClone(hudRecord.document);
await fs.writeFile(path.join(proof,'hud-before.json'),JSON.stringify(hudRecord));
const children=hud.prefabs['rs-prefab-resources'].root.children,bar=children.find(n=>n.id==='rs-stun');
if(!bar)throw Error('Missing authored HUD stun bar');
for(const id of Object.keys(hud.assets))if(id==='rs-svg-stun-earth-fill')delete hud.assets[id];
hud.assets['rs-svg-stun-yellow-fill']={id:'rs-svg-stun-yellow-fill',name:'晕眩 · 半透明黄色',viewBox:[0,0,212,4],scaleMode:'stretch',source:stunOverlaySvg(212,4)};
bar.type='Svg';bar.svgAsset='rs-svg-stun-yellow-fill';bar.value=0;bar.style.color=STUN_YELLOW;
const value=children.find(n=>n.id==='rs-stun-value');value.text='0 / 400';value.name=value.text;
hud.provenance??={};hud.provenance.stunFill={color:STUN_YELLOW,opacity:.55,runtime:'clamp(stun buildup / maximum life, 0, 1)',ruleChanges:false};
const hudSaved=await save(hud,hudRecord);
for(const file of ['UIAuthoring/RuleStudio3D.uialpha.json','CustomTools/UICreatorAlpha/Screen/RuleStudio-HUD/hud.uialpha.json'])await fs.writeFile(path.join(root,file),JSON.stringify(hud,null,2));
const player=createPlayerStunProject();await save(player,await repo.pointer(player.id));
await fs.writeFile(path.join(proof,'yellow.svg'),stunOverlaySvg(212,4));
await fs.writeFile(path.join(proof,'authoring.json'),JSON.stringify({world:{id:world.id,revision:worldSaved.revision},hud:{id:hud.id,revision:hudSaved.revision}},null,2));
console.log(JSON.stringify({worldRevision:worldSaved.revision,hudRevision:hudSaved.revision,color:STUN_YELLOW,opacity:.55}));
