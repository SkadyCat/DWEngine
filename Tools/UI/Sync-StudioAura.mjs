// Reuse the approved UICreator aura layer and motion in the Studio belt.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createDocument, validateDocument} from '../../CustomTools/UICreatorAlpha/src/core/model.js';
const root = path.resolve(import.meta.dirname, '../..');
const source = JSON.parse(await fs.readFile(path.join(root, 'UIAuthoring/RecentGameplay.uialpha.json'), 'utf8'));
function find(node, id) { return node.id === id ? node : node.children?.map(child => find(child, id)).find(Boolean); }
const layer = structuredClone(find(source.root, 'aura-slot-active'));
if (!layer) throw Error('UICreator aura-slot-active layer is missing');
const doc = createDocument('Studio · 光环激活流光');
doc.id = 'studio-aura-state'; doc.viewport = {width: 64, height: 64, background: 'transparent'};
doc.root.id = 'studio-aura-state-root';
doc.root.layout = {...doc.root.layout, width: 64, height: 64};
doc.root.children = [layer];
doc.sounds = {};
layer.motion.enabled = true;
doc.motions = {[layer.motion.assetId]: structuredClone(source.motions[layer.motion.assetId])};
doc.source = {document: 'UIAuthoring/RecentGameplay.uialpha.json', node: layer.id};
const errors = validateDocument(doc); if (errors.length) throw Error(errors.join('\n'));
await fs.writeFile(path.join(root, 'UIAuthoring/StudioAuraState.uialpha.json'), JSON.stringify(doc, null, 2) + '\n');
await fs.writeFile(path.join(root, 'CustomTools/UICreatorAlpha/src/assets/rulestudio-hud/aura-state.js'),
  '// Generated by Tools/UI/Sync-StudioAura.mjs from the UICreator source document.\nexport const auraStateDocument = ' + JSON.stringify(doc) + ';\n');
console.log('UICreator aura layer synchronized to Studio');
