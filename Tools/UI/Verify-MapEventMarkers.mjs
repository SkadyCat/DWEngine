import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const {chromium} = await import(pathToFileURL(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs')));
const root = path.resolve(import.meta.dirname, '../..'), output = path.join(root, 'Saved/Verification/MapEventMarkers');
await fs.mkdir(output, {recursive: true});
const browser = await chromium.launch({headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
try {
  const context = await browser.newContext({viewport: {width: 1600, height: 1000}, reducedMotion: 'reduce'});
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5354/dev/map-events-qa.html');
  await page.locator('.atlas-event-pin').first().waitFor();
  await page.screenshot({path: path.join(output, 'world.png')});
  const worldLabels = await page.locator('.atlas-event-pin svg.map-event-badges').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')));
  for (const name of ['拓荒商人','百炼法坛','万相合成祭坛','遗珍神龛','封印宝库']) assert.ok(worldLabels.some(label => label.includes(name)), name);
  await page.locator('.qa-map-controls').getByRole('button', {name: '地牢地图', exact: true}).click();
  await page.locator('[data-map-events="panel"] [data-map-event]').first().waitFor();
  const read = mode => page.locator(`[data-map-events="${mode}"] [data-map-event]`).evaluateAll(nodes => nodes.map(node => ({id: node.getAttribute('data-map-event'), kind: node.getAttribute('data-event-kind'), completed: node.getAttribute('data-completed'), transform: node.getAttribute('transform')})));
  const before = await read('panel'), mini = await read('mini');
  assert.deepEqual(before.map(event => event.id), mini.map(event => event.id));
  assert.deepEqual(new Set(before.map(event => event.kind)), new Set(['altar','vault']));
  await page.screenshot({path: path.join(output, 'local.png')});
  await page.getByRole('button', {name: '放大地牢地图', exact: true}).click();
  const zoomed = await read('panel');
  assert.ok(zoomed.some((event, index) => event.transform !== before[index].transform));
  await page.locator('.qa-map-controls').getByRole('button', {name: '切换完成状态'}).click();
  await page.waitForFunction(() => [...document.querySelectorAll('[data-map-events="panel"] [data-map-event]')].every(node => node.getAttribute('data-completed') === 'true'));
  const completed = await read('panel');
  await page.screenshot({path: path.join(output, 'completed.png')});
  await page.locator('.qa-map-controls').getByRole('button', {name: '世界地图', exact: true}).click();
  await page.locator('.atlas-region-events').waitFor();
  assert.equal(await page.locator('.atlas-region-events small').filter({hasText: '已完成'}).count(), 2);
  await page.screenshot({path: path.join(output, 'world-completed.png')});
  assert.deepEqual(errors, []);
  const receipt = {isolatedOrigin: 'http://127.0.0.1:5354', worldLabels, before, mini, zoomed, completed, pageErrors: errors};
  await fs.writeFile(path.join(output, 'receipt.json'), JSON.stringify(receipt, null, 2));
  console.log(JSON.stringify({worldRegionsWithEvents: worldLabels.length, localEventKinds: before.map(event => event.kind), zoom: true, completion: true, pageErrors: errors, output}));
  await context.close();
} finally { await browser.close(); }
