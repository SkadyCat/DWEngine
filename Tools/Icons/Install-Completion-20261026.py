"""Archive imagegen originals, normalize PNGs, and pack the historical 3x3 format.
Only delivery resizing/packing happens here; artwork is generated by image_gen.
"""
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / 'CustomTools/RuleStudio/public/assets/icons/warcraft-v1'
PROOF = ROOT / 'Saved/Verification/IconCompletion'
BATCH = 'opus-20261026'
records = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8-sig'))
assert len(records) == 32 and len({(r['kind'], r['id']) for r in records}) == 32
PROOF.mkdir(parents=True, exist_ok=True)

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def write_png(image, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        backup = PROOF / 'previous' / target.relative_to(ROOT)
        backup.parent.mkdir(parents=True, exist_ok=True)
        if not backup.exists():
            shutil.copy2(target, backup)
    image.save(target, optimize=True)

entries, receipts, sheets = [], [], []
for i, record in enumerate(records):
    match = re.search(r'as ([A-Z]:\\[^\r\n]+\.png) by default', record['output_hint'])
    assert match, record['id']
    source = Path(match.group(1))
    archive = WEB / 'source' / BATCH / record['kind'] / (record['id'] + '.png')
    archive.parent.mkdir(parents=True, exist_ok=True)
    if archive.exists():
        assert sha(source) == sha(archive), 'Conflicting archived original'
    else:
        shutil.copy2(source, archive)
    original = Image.open(archive)
    assert original.width == original.height, record['id']
    if original.mode == 'RGBA':
        assert original.getchannel('A').getextrema() == (255, 255), record['id']
    icon = original.convert('RGB').resize((256, 256), Image.Resampling.LANCZOS)
    relative = Path(record['kind']) / (record['id'] + '.png')
    write_png(icon, WEB / relative)
    write_png(icon, ROOT / 'Content/OpusIcons' / relative)
    sheet_id = BATCH + '-' + str(i // 9 + 1).zfill(2)
    entries.append(dict(kind=record['kind'], id=record['id'], name=record['name'],
                        sheet=sheet_id, row=i % 9 // 3, column=i % 3,
                        src='/assets/icons/warcraft-v1/' + relative.as_posix(),
                        sourceImage=archive.relative_to(WEB).as_posix(),
                        authoredBy='built-in image_gen', batch=BATCH))
    receipts.append(dict(id=record['id'], kind=record['kind'], name=record['name'],
                         original=archive.relative_to(ROOT).as_posix(),
                         originalSha256=sha(archive), png=relative.as_posix(),
                         pngSha256=sha(WEB / relative),
                         nativeSha256=sha(ROOT / 'Content/OpusIcons' / relative),
                         prompt=record['prompt']))

for start in range(0, len(entries), 9):
    group = entries[start:start + 9]
    sheet_id = group[0]['sheet']
    atlas = Image.new('RGB', (768, 768), '#080b11')
    for i, entry in enumerate(group):
        icon = Image.open(WEB / entry['kind'] / (entry['id'] + '.png')).convert('RGB')
        atlas.paste(icon, (i % 3 * 256, i // 3 * 256))
    write_png(atlas, WEB / 'sheets' / (sheet_id + '.png'))
    write_png(atlas, WEB / 'source' / (sheet_id + '.png'))
    sheets.append(dict(id=sheet_id, name='补齐专属图标 ' + str(start // 9 + 1),
                       source=sheet_id + '.png', x=[0, 256, 512, 768], y=[0, 256, 512, 768],
                       entries=[[e['kind'], e['id'], e['name']] for e in group],
                       originalImages=[e['sourceImage'] for e in group],
                       emptyCells=list(range(len(group), 9))))

# Maps share one authored base. Tier and rarity remain live UI labels/borders.
map_icon = Image.open(WEB / 'item/map.png').convert('RGB')
for definition in sorted((ROOT / 'Content/Rules/Items').glob('map_*.json')):
    doc = json.loads(definition.read_text(encoding='utf-8-sig'))
    if doc.get('category') != 'map':
        continue
    relative = Path('item') / (doc['id'] + '.png')
    write_png(map_icon, WEB / relative)
    write_png(map_icon, ROOT / 'Content/OpusIcons' / relative)
    entries.append(dict(kind='item', id=doc['id'], name=doc['name'], sheet=None,
                        row=None, column=None, src='/assets/icons/warcraft-v1/' + relative.as_posix(),
                        copyFrom='item/map.png', sharedBase='map', batch=BATCH))

# The existing dedicated taunt artwork is retained, only its legacy 128px
# delivery size is normalized to the already documented 256px contract.
for base in (WEB, ROOT / 'Content/OpusIcons'):
    target = base / 'skill/taunt.png'
    image = Image.open(target)
    if image.size != (256, 256):
        write_png(image.convert('RGBA').resize((256, 256), Image.Resampling.LANCZOS), target)

catalog = ROOT / 'CustomTools/RuleStudio/public/icon-completion-20261026.mjs'
catalog.write_text('// Original image_gen art; map variants share their authored base.\n'
                   'export const COMPLETION_SHEETS=' + json.dumps(sheets, ensure_ascii=False, indent=2) + ';\n'
                   'export const COMPLETION_ENTRIES=' + json.dumps(entries, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
doc = dict(generator='built-in image_gen', batch=BATCH, styleSpec='docs/game-icons.md',
           stylePrompts='docs/game-icons-prompts.md',
           sourcePrompts='docs/game-icons-completion-20261026.json#newArt',
           normalization='Opaque RGB, Lanczos 256x256; no artwork edits',
           newArt=receipts, sharedMapVariants=len(entries) - len(records),
           sheets=sheets, entries=entries)
(PROOF / 'install-receipt.json').write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding='utf-8')
history = ROOT / 'CustomTools/RuleStudio/docs/game-icons-completion-20261026.json'
history.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding='utf-8')

# Review output has 128px icons and actual 32px samples; labels stay outside art.
canvas = Image.new('RGB', (1280, 4 * 230), '#0b1019')
draw = ImageDraw.Draw(canvas)
font = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 15)
for i, record in enumerate(records):
    x, y = (i % 8) * 160 + 16, (i // 8) * 230 + 12
    icon = Image.open(WEB / record['kind'] / (record['id'] + '.png')).convert('RGB')
    canvas.paste(icon.resize((128, 128), Image.Resampling.LANCZOS), (x, y))
    draw.text((x, y + 136), record['name'], font=font, fill='#dce7f7')
    canvas.paste(icon.resize((32, 32), Image.Resampling.LANCZOS), (x, y + 165))
    draw.text((x + 40, y + 172), '32px', font=font, fill='#94a3b8')
canvas.save(PROOF / 'gallery.png')
print(json.dumps(dict(art=len(records), mapVariants=doc['sharedMapVariants'], sheets=len(sheets),
                      gallery=str(PROOF / 'gallery.png')), ensure_ascii=False))
