"""Trace local RuleStudio icon artwork into standalone SVG paths (build-time only).

Install the pinned tool into work/vector-tools with:
python -m pip install --target work/vector-tools vtracer==0.6.15
"""
import base64
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'work/vector-tools'))
import vtracer
from PIL import Image

SOURCE = ROOT.parent / 'RuleStudio/public/assets/icons/warcraft-v1'
SOURCES = {
    'staff': 'equipment/frostthorn_staff', 'boots': 'equipment/warden_boots',
    'gloves': 'equipment/cinder_guard_gloves', 'helmet': 'equipment/embers_echo_4_helmet',
    'amulet': 'equipment/cinder_guard_amulet', 'poison': 'equipment/venomglass_flask',
    'belt': 'equipment/cinder_guard_belt', 'fire-boots': 'equipment/cinder_surge_steps',
    'fire-helmet': 'equipment/cinder_surge_crown', 'sword': 'skill/player_slash',
    'axe': 'skill/earth_wave', 'iron-boots': 'equipment/cinder_guard_boots',
    'void': 'skill/spirit_servant', 'fire-belt': 'equipment/cinder_surge_belt',
    'flame': 'skill/flame_burst', 'ice': 'skill/frost_lance', 'sentinel': 'skill/sentinel',
    'shield': 'equipment/cinder_guard_offhand', 'chest': 'equipment/cinder_guard_chest',
    'ring': 'equipment/cinder_guard_ring', 'potion': 'item/healing_draught',
    'stone-green': 'item/chaos_orb', 'stone-gold': 'item/quad_affix_orb',
    'stone-purple': 'item/spirit_stone_high', 'stone-blue': 'item/spirit_stone_mid',
    'omen-fire': 'item/omen_elemental', 'omen-ice': 'item/omen_affliction',
    **{f'original-{name}': f'item/{name}' for name in ['omen_vitality', 'omen_proc', 'omen_barrier', 'omen_mind', 'omen_martial', 'omen_elemental', 'omen_offense', 'omen_guard', 'omen_ballistic', 'omen_affliction', 'berserk_draught']}
}
output = ROOT / 'src/assets/rulestudio-hud/svg/original-art'
output.mkdir(parents=True, exist_ok=True)
bundle, manifest = {}, []
for name, relative in SOURCES.items():
    source = SOURCE / (relative + '.png')
    image = Image.open(source).convert('RGBA').resize((96, 96), Image.Resampling.LANCZOS)
    svg = vtracer.convert_pixels_to_svg(list(image.getdata()), image.size, colormode='color', hierarchical='stacked', mode='spline', filter_speckle=1, color_precision=6, layer_difference=4, length_threshold=3.5, path_precision=1)
    svg = re.sub(r'^.*?<svg[^>]*>', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96">', svg, count=1, flags=re.S)
    svg = re.sub(r'\s+(?=<)', '', svg).replace(' Z ', 'Z').replace(' L', 'L').replace(' C', 'C')
    hue = {'stone-green': (200, .65), 'stone-blue': (320, 1), 'stone-purple': (140, 1)}.get(name)
    if hue:
        svg = svg.replace('<path', f'<defs><filter id="grade" color-interpolation-filters="sRGB"><feColorMatrix type="hueRotate" values="{hue[0]}"/><feColorMatrix type="saturate" values="{hue[1]}"/></filter></defs><g filter="url(#grade)"><path', 1).replace('</svg>', '</g></svg>')
    assert '<image' not in svg and '<foreignObject' not in svg
    (output / (name + '.svg')).write_text(svg, encoding='utf-8')
    bundle[name] = svg
    manifest.append({'id': name, 'source': str(source), 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'sourceSize': list(Image.open(source).size), 'traceSize': [96, 96], 'paths': svg.count('<path'), 'bytes': len(svg.encode())})
(ROOT / 'src/assets/rulestudio-hud/traced-icons.js').write_text('// Generated by scripts/trace-battle-icons.py. SVG paths, no embedded bitmaps.\nexport const tracedIcons=' + json.dumps(bundle, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
(output / 'provenance.json').write_text(json.dumps({'tool': 'vtracer 0.6.15', 'icons': manifest}, ensure_ascii=False, indent=2), encoding='utf-8')

# A local visual audit: the originals are used only here, never inside UI SVG assets.
cards = []
for relative in ['equipment/'+n for n in ['cinder_guard_gloves','fire_turret_clockwork_gloves','bloodthirst_gauntlets','cinder_guard_boots','embers_echo_1_boots','spiritcall_bell']] + ['item/' + n for n in ['omen_vitality','spirit_stone_mid','quad_affix_orb','chaos_orb','omen_barrier','omen_mind','omen_martial','omen_elemental','omen_offense','omen_guard','omen_proc','omen_ballistic','omen_affliction']]:
    data = base64.b64encode((SOURCE / (relative + '.png')).read_bytes()).decode()
    cards.append(f'<figure><img width="64" height="64" src="data:image/png;base64,{data}"><figcaption>{relative}</figcaption></figure>')
(ROOT / 'examples/faithfulness-art.html').write_text('<!doctype html><meta charset="utf-8"><title>原图标核对</title><style>body{background:#101722;color:#cdd7e6;font:12px Segoe UI}main{display:grid;grid-template-columns:repeat(7,150px);gap:8px}figure{margin:0;padding:10px;border:1px solid #334054}figcaption{overflow-wrap:anywhere}</style><main>' + ''.join(cards) + '</main>', encoding='utf-8')
print(json.dumps({'icons':len(bundle),'bytes':sum(m['bytes'] for m in manifest),'paths':sum(m['paths'] for m in manifest)}))
